/** Lazily built lookup, so importing this module stays cheap. */
let downloadIndex: Map<string, number> | null = null;

function index(): Map<string, number> {
  if (!downloadIndex) {
    downloadIndex = new Map(POPULAR_PACKAGES.map(([name, downloads]) => [name, downloads]));
  }
  return downloadIndex;
}

let nameCache: string[] | null = null;

/** Every popular package name. */
export function popularNames(): readonly string[] {
  if (!nameCache) nameCache = POPULAR_PACKAGES.map(([name]) => name);
  return nameCache;
}

/** True when this exact name is on the list. */
export function isPopularPackage(name: string): boolean {
  return index().has(name);
}

/** Weekly downloads for a listed package, or 0 when it is not on the list. */
export function downloadsFor(name: string): number {
  return index().get(name) ?? 0;
}

